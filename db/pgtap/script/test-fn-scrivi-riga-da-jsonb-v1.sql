-- I due BB della scrittura da payload jsonb:
--   script.fn_scrivi_riga_da_jsonb   (20261017-05; rilettura 20261018-34)
--   script.fn_prima_chiave_estranea  (20261017-06)
-- e i tre punti che li usano al posto delle copie (regola del 2):
--   config.fn_pannello_scrivi (20261017-07), vendite.fn_create_contratto
--   (20261017-08), anagrafiche.fn_crea_emittente_fiscale (20261017-09).
--   Brief: brief-db-processi-accensione-per-ambiente (§5-ter.1, 2b-1).
--
-- ⭐ Il caso si COSTRUISCE: una tabella temporanea con un default, una
--   colonna NOT NULL e una chiave diversa da id. Nessun dato pescato.
--
-- Elenco test (plan 27):
--   forma
--    1) fn_scrivi_riga_da_jsonb e' INVOKER
--    2) fn_prima_chiave_estranea e' IMMUTABLE, LANGUAGE sql
--   INSERT
--    3) le sole chiavi del payload; l'assente prende il DEFAULT
--    4) i valori si convertono sul tipo della colonna (testo -> integer, date)
--    5) payload vuoto: DEFAULT VALUES
--    6) una chiave che non e' una colonna: 42703 (il filtro e' del chiamante)
--   UPDATE
--    7) per id: solo le chiavi del payload, le altre invariate
--    8) per una chiave diversa da id (codice)
--    9) riga che non c'e': NULL, nessuna scrittura
--   10) payload vuoto: nessuna scrittura, torna la riga com'e'
--   11) un valore NULL esplicito scrive NULL (non e' «assente»)
--   chiamata malformata -> E_SCRIPT_CHIAMATA_NON_VALIDA
--   12) tabella NULL
--   13) dati che non sono un oggetto
--   14) chiave di riga vuota
--   la prima chiave estranea
--   15) tutte ammesse: NULL
--   16) la prima in ordine alfabetico
--   17) elenco NULL: nessuna ammessa
--   18) payload vuoto: NULL
--   i chiamanti (strutturali: le copie sono ritirate)
--   19) il pannello chiama i due BB e non compone piu' l'INSERT
--   20) la madre del contratto chiama il BB e non compone piu' l'INSERT
--   21) il verbo dell'emittente chiama i due BB
--   22) nessuna di queste tre contiene piu' jsonb_populate_record
--   la rilettura a istruzione finita (p_rileggi_per, 20261018-34)
--   23) INSERT riletta per la chiave: la riga col DEFAULT e l'id
--   24) una colonna della chiave assente dai dati: E_SCRIPT_CHIAMATA_NON_VALIDA
--   25) rilettura con p_dove (un UPDATE): E_SCRIPT_CHIAMATA_NON_VALIDA
--   26) il perche': sotto una policy che non lascia vedere la riga appena
--       scritta, il RETURNING muore (42501)
--   27) ... e la rilettura dice che la riga non si vede:
--       E_SCRIPT_CHIAMATA_NON_VALIDA, non un NULL muto
-- ------------------------------------------------------------

BEGIN;

SET CONSTRAINTS ALL IMMEDIATE;

DO $ctx$ BEGIN PERFORM script.fn_pgtap_set_contesto_operatore(); END $ctx$;

SELECT plan(27);


CREATE OR REPLACE FUNCTION pg_temp.sqlstate_di(p_sql text) RETURNS text
LANGUAGE plpgsql AS $$
BEGIN
    EXECUTE p_sql;
    RETURN NULL;
EXCEPTION WHEN OTHERS THEN
    RETURN SQLSTATE;
END $$;

-- Il caso: una tabella con un default, una NOT NULL senza default, una data,
-- e una chiave naturale diversa da id.
CREATE TEMP TABLE t_riga (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codice  text    NOT NULL UNIQUE,
    stato   text    NOT NULL DEFAULT 'BOZZA',
    qta     integer,
    dal     date,
    nota    text    DEFAULT 'senza nota'
);

-- ============================================================
-- Forma
-- ============================================================
SELECT is(
    (SELECT p.prosecdef FROM pg_proc p
      WHERE p.oid = 'script.fn_scrivi_riga_da_jsonb(regclass, jsonb, jsonb, text[])'::regprocedure),
    false,
    '1. fn_scrivi_riga_da_jsonb e'' INVOKER: scrive coi privilegi di chi chiama');

SELECT is(
    (SELECT format('%s|%s', p.provolatile, l.lanname)
       FROM pg_proc p JOIN pg_language l ON l.oid = p.prolang
      WHERE p.oid = 'script.fn_prima_chiave_estranea(jsonb, text[])'::regprocedure),
    'i|sql',
    '2. fn_prima_chiave_estranea e'' IMMUTABLE, LANGUAGE sql');

-- ============================================================
-- INSERT
-- ============================================================
SELECT is(
    (SELECT format('%s|%s|%s', r ->> 'codice', r ->> 'stato', r ->> 'nota')
       FROM script.fn_scrivi_riga_da_jsonb('pg_temp.t_riga'::regclass,
                                           '{"codice": "A", "nota": "scritta"}'::jsonb) AS r),
    'A|BOZZA|scritta',
    '3. INSERT: le sole chiavi del payload, l''assente (stato) al DEFAULT');

SELECT is(
    (SELECT format('%s|%s', jsonb_typeof(r -> 'qta'), r ->> 'dal')
       FROM script.fn_scrivi_riga_da_jsonb('pg_temp.t_riga'::regclass,
                                           '{"codice": "B", "qta": "7", "dal": "2026-10-17"}'::jsonb) AS r),
    'number|2026-10-17',
    '4. i valori si convertono sul tipo della colonna (testo -> integer, date)');

CREATE TEMP TABLE t_vuota (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           nota text DEFAULT 'default');
SELECT is(
    (SELECT r ->> 'nota'
       FROM script.fn_scrivi_riga_da_jsonb('pg_temp.t_vuota'::regclass, '{}'::jsonb) AS r),
    'default',
    '5. payload vuoto: INSERT DEFAULT VALUES');

SELECT is(
    pg_temp.sqlstate_di($$SELECT script.fn_scrivi_riga_da_jsonb('pg_temp.t_riga'::regclass,
                                                                '{"codice": "C", "colonna_che_non_ce": 1}'::jsonb)$$),
    '42703',
    '6. una chiave che non e'' una colonna: 42703 (scegliere le chiavi e'' del chiamante)');

-- ============================================================
-- UPDATE
-- ============================================================
SELECT is(
    (SELECT format('%s|%s|%s', r ->> 'stato', r ->> 'nota', r ->> 'qta')
       FROM script.fn_scrivi_riga_da_jsonb(
                'pg_temp.t_riga'::regclass,
                '{"stato": "ATTIVO"}'::jsonb,
                jsonb_build_object('id', (SELECT t.id FROM t_riga t WHERE t.codice = 'B'))) AS r),
    'ATTIVO|senza nota|7',
    '7. UPDATE per id: solo la chiave del payload, le altre invariate');

SELECT is(
    (SELECT r ->> 'qta'
       FROM script.fn_scrivi_riga_da_jsonb('pg_temp.t_riga'::regclass,
                                           '{"qta": 3}'::jsonb,
                                           '{"codice": "A"}'::jsonb) AS r),
    '3',
    '8. UPDATE per una chiave diversa da id (codice)');

SELECT is(
    script.fn_scrivi_riga_da_jsonb('pg_temp.t_riga'::regclass,
                                   '{"qta": 99}'::jsonb,
                                   '{"codice": "NON-CE"}'::jsonb),
    NULL::jsonb,
    '9. UPDATE di una riga che non c''e'': NULL, nessuna scrittura');

SELECT is(
    (SELECT r ->> 'qta'
       FROM script.fn_scrivi_riga_da_jsonb('pg_temp.t_riga'::regclass,
                                           '{}'::jsonb,
                                           '{"codice": "A"}'::jsonb) AS r),
    '3',
    '10. UPDATE con payload vuoto: nessuna scrittura, torna la riga com''e''');

SELECT is(
    (SELECT r -> 'nota'
       FROM script.fn_scrivi_riga_da_jsonb('pg_temp.t_riga'::regclass,
                                           '{"nota": null}'::jsonb,
                                           '{"codice": "A"}'::jsonb) AS r),
    'null'::jsonb,
    '11. un NULL esplicito scrive NULL: presente e vuoto non e'' assente');

-- ============================================================
-- Chiamata malformata
-- ============================================================
SELECT is(dbops.fn_pgtap_codice_errore($$SELECT script.fn_scrivi_riga_da_jsonb(NULL, '{}'::jsonb)$$),
          'E_SCRIPT_CHIAMATA_NON_VALIDA', '12. tabella NULL: E_SCRIPT_CHIAMATA_NON_VALIDA');

SELECT is(dbops.fn_pgtap_codice_errore($$SELECT script.fn_scrivi_riga_da_jsonb('pg_temp.t_riga'::regclass, '[1]'::jsonb)$$),
          'E_SCRIPT_CHIAMATA_NON_VALIDA', '13. dati che non sono un oggetto: E_SCRIPT_CHIAMATA_NON_VALIDA');

SELECT is(dbops.fn_pgtap_codice_errore($$SELECT script.fn_scrivi_riga_da_jsonb('pg_temp.t_riga'::regclass, '{"qta": 1}'::jsonb, '{}'::jsonb)$$),
          'E_SCRIPT_CHIAMATA_NON_VALIDA', '14. chiave di riga vuota: E_SCRIPT_CHIAMATA_NON_VALIDA');

-- ============================================================
-- La prima chiave estranea
-- ============================================================
SELECT is(script.fn_prima_chiave_estranea('{"a": 1, "b": 2}'::jsonb, ARRAY['a', 'b', 'c']),
          NULL::text, '15. tutte ammesse: NULL');

SELECT is(script.fn_prima_chiave_estranea('{"z": 1, "m": 2, "a": 3}'::jsonb, ARRAY['a']),
          'm', '16. la prima estranea in ordine alfabetico');

SELECT is(script.fn_prima_chiave_estranea('{"a": 1}'::jsonb, NULL),
          'a', '17. elenco NULL: nessuna chiave ammessa');

SELECT is(script.fn_prima_chiave_estranea('{}'::jsonb, ARRAY['a']),
          NULL::text, '18. payload vuoto: NULL');

-- ============================================================
-- I chiamanti: le copie sono ritirate (sul corpo, senza commenti)
-- ============================================================
CREATE OR REPLACE FUNCTION pg_temp.corpo(p regprocedure) RETURNS text
LANGUAGE sql AS $$
    SELECT regexp_replace(p2.prosrc, '--[^\n]*', '', 'g') FROM pg_proc p2 WHERE p2.oid = p
$$;

SELECT ok(
    pg_temp.corpo('config.fn_pannello_scrivi(text, bigint, jsonb)'::regprocedure) ~ 'script\.fn_scrivi_riga_da_jsonb\('
    AND pg_temp.corpo('config.fn_pannello_scrivi(text, bigint, jsonb)'::regprocedure) ~ 'script\.fn_prima_chiave_estranea\('
    AND pg_temp.corpo('config.fn_pannello_scrivi(text, bigint, jsonb)'::regprocedure) !~* 'INSERT INTO',
    '19. il pannello chiama i due BB e non compone piu'' l''INSERT');

SELECT ok(
    pg_temp.corpo('vendite.fn_create_contratto(jsonb, jsonb)'::regprocedure) ~ 'script\.fn_scrivi_riga_da_jsonb\('
    AND pg_temp.corpo('vendite.fn_create_contratto(jsonb, jsonb)'::regprocedure) !~* 'INSERT INTO',
    '20. la madre del contratto chiama il BB e non compone piu'' l''INSERT');

SELECT ok(
    pg_temp.corpo('anagrafiche.fn_crea_emittente_fiscale(uuid, character varying, jsonb)'::regprocedure) ~ 'script\.fn_scrivi_riga_da_jsonb\('
    AND pg_temp.corpo('anagrafiche.fn_crea_emittente_fiscale(uuid, character varying, jsonb)'::regprocedure) ~ 'script\.fn_prima_chiave_estranea\(',
    '21. il verbo dell''emittente chiama i due BB');

SELECT is(
    (SELECT count(*)::int
       FROM unnest(ARRAY['config.fn_pannello_scrivi(text, bigint, jsonb)'::regprocedure,
                         'vendite.fn_create_contratto(jsonb, jsonb)'::regprocedure,
                         'anagrafiche.fn_crea_emittente_fiscale(uuid, character varying, jsonb)'::regprocedure]) AS f
      WHERE pg_temp.corpo(f) ~* 'jsonb_populate_record'),
    0,
    '22. nessuno dei tre compone piu'' jsonb_populate_record: la conversione ha una sede sola');

-- ============================================================
-- La rilettura a istruzione finita (p_rileggi_per)
-- ============================================================
SELECT is(
    (SELECT format('%s|%s|%s', r ->> 'codice', r ->> 'stato', (r ->> 'id') IS NOT NULL)
       FROM script.fn_scrivi_riga_da_jsonb('pg_temp.t_riga'::regclass,
                                           '{"codice": "RILETTA"}'::jsonb, NULL,
                                           ARRAY['codice']) AS r),
    'RILETTA|BOZZA|t',   -- format() di un boolean: t
    '23. INSERT riletta per la chiave: la riga col DEFAULT e l''id');

SELECT is(
    dbops.fn_pgtap_codice_errore($$SELECT script.fn_scrivi_riga_da_jsonb('pg_temp.t_riga'::regclass,
        '{"codice": "SENZA_CHIAVE"}'::jsonb, NULL, ARRAY['qta'])$$),
    'E_SCRIPT_CHIAMATA_NON_VALIDA',
    '24. una colonna della chiave assente dai dati: E_SCRIPT_CHIAMATA_NON_VALIDA');

SELECT is(
    dbops.fn_pgtap_codice_errore($$SELECT script.fn_scrivi_riga_da_jsonb('pg_temp.t_riga'::regclass,
        '{"nota": "x"}'::jsonb, '{"codice": "A"}'::jsonb, ARRAY['codice'])$$),
    'E_SCRIPT_CHIAMATA_NON_VALIDA',
    '25. rilettura con p_dove (un UPDATE): E_SCRIPT_CHIAMATA_NON_VALIDA');

-- Il caso del billing account, costruito: una tabella sotto una policy che
-- ammette la scrittura e non lascia vedere la riga (FORCE: vale anche per chi
-- la possiede).
CREATE TEMP TABLE t_cieca (codice text PRIMARY KEY, nota text);
ALTER TABLE t_cieca ENABLE ROW LEVEL SECURITY;
ALTER TABLE t_cieca FORCE ROW LEVEL SECURITY;
CREATE POLICY p_scrive ON t_cieca FOR INSERT WITH CHECK (true);
CREATE POLICY p_non_vede ON t_cieca FOR SELECT USING (false);

SELECT is(
    pg_temp.sqlstate_di($$SELECT script.fn_scrivi_riga_da_jsonb('pg_temp.t_cieca'::regclass,
        '{"codice": "R1"}'::jsonb)$$),
    '42501',
    '26. il perche'': sotto una policy che non lascia vedere la riga, il RETURNING muore (42501)');

SELECT is(
    dbops.fn_pgtap_codice_errore($$SELECT script.fn_scrivi_riga_da_jsonb('pg_temp.t_cieca'::regclass,
        '{"codice": "R2"}'::jsonb, NULL, ARRAY['codice'])$$),
    'E_SCRIPT_CHIAMATA_NON_VALIDA',
    '27. ... e la rilettura dice che la riga non si vede, non un NULL muto');

SELECT * FROM finish();

ROLLBACK;
