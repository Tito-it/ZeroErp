--
-- Test: dbops.fn_run_automations_delete_block lascia traccia anche nel giro vero
--
-- ChangeSet: 20_code/dbops/20261104-52
-- Brief: brief-db-revisione-dbops, D41 (giro 1, blocco 1c)
--
-- ⛔ IL DIFETTO CHE CHIUDE. Il dry run scriveva in dbops.audit_log, il giro
--   vero no: un trigger creato davvero non lasciava nessuna riga, e una tabella
--   configurata ma sparita si vedeva solo nel dry run.
--
-- La fixture: una tabella vera e una configurata ma inesistente, tutte e due
--   in ambito e in dbops.automation_delete_block. Il ROLLBACK porta via tutto.
--
-- Elenco test (plan 7):
--   IL DRY RUN
--    1 : la tabella vera: DRYRUN, il trigger sarebbe creato
--    2 : la tabella sparita: WARN TABLE_NOT_FOUND (prima era DRYRUN, come
--        un'azione che sarebbe avvenuta)
--    3 : il dry run non crea il trigger
--   IL GIRO VERO
--    4 : il trigger c'e'
--    5 : ⭐ e c'e' una riga OK CREATE_TRIGGER (prima nessuna)
--    6 : ⭐ la tabella sparita lascia WARN TABLE_NOT_FOUND anche qui (prima
--        nessuna riga)
--    7 : un secondo giro, col trigger gia' presente, non registra niente: non
--        e' un'azione
-- ------------------------------------------------------------

BEGIN;

-- ⚠️ Vincoli DIFFERITI: senza questa riga il test smetterebbe di verificarli.
--   Un trigger DEFERRABLE INITIALLY DEFERRED scatta al COMMIT, e qui il COMMIT
--   non arriva mai (si chiude in ROLLBACK). Brief: brief-db-pgtap-runner-rls-baseline §19.
SET CONSTRAINTS ALL IMMEDIATE;

-- Contesto applicativo: il preambolo e' un contratto (guardrail_pgtap_preambolo).
DO $ctx$ BEGIN PERFORM script.fn_pgtap_set_contesto_operatore(); END $ctx$;

SELECT plan(7);

-- ============================================================
-- Fixture
-- ============================================================
CREATE TABLE dbops.tst_delete_block_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payload text
);

INSERT INTO dbops.automation_scope (schema_name, table_like)
VALUES ('dbops', 'tst_delete_block_audit'),
       ('dbops', 'tst_delete_block_sparita')
ON CONFLICT DO NOTHING;

INSERT INTO dbops.automation_delete_block (schema_name, table_name, guc_key, enabled)
VALUES ('dbops', 'tst_delete_block_audit',   'zeroerp.pgtap_delete_block', true),
       ('dbops', 'tst_delete_block_sparita', 'zeroerp.pgtap_delete_block', true);

CREATE TEMP TABLE _prima ON COMMIT DROP AS
SELECT COALESCE(max(id), 0) AS ultimo_id FROM dbops.audit_log;

-- ============================================================
-- 1-3. Il dry run
-- ============================================================
SELECT dbops.fn_run_automations_delete_block('AUTO', ARRAY['dbops'], true);

SELECT ok(EXISTS (
    SELECT 1 FROM dbops.audit_log a
     WHERE a.id > (SELECT ultimo_id FROM _prima)
       AND a.function_name = 'dbops.fn_run_automations_delete_block'
       AND a.status = 'DRYRUN' AND a.dry_run
       AND a.params ->> 'table'  = 'dbops.tst_delete_block_audit'
       AND a.params ->> 'action' = 'DRYRUN_CREATE_TRIGGER'),
    '1. dry run, tabella vera: una riga DRYRUN, il trigger sarebbe creato');

SELECT ok(EXISTS (
    SELECT 1 FROM dbops.audit_log a
     WHERE a.id > (SELECT ultimo_id FROM _prima)
       AND a.function_name = 'dbops.fn_run_automations_delete_block'
       AND a.status = 'WARN' AND a.dry_run
       AND a.params ->> 'table'  = 'dbops.tst_delete_block_sparita'
       AND a.params ->> 'reason' = 'TABLE_NOT_FOUND'),
    '2. dry run, tabella sparita: WARN TABLE_NOT_FOUND, un salto e non un''azione');

SELECT hasnt_trigger('dbops', 'tst_delete_block_audit', 'trg_tst_delete_block_audit_a10_delete_block_dlt',
    '3. il dry run non crea il trigger');

-- ============================================================
-- 4-7. Il giro vero
-- ============================================================
TRUNCATE _prima;
INSERT INTO _prima SELECT COALESCE(max(id), 0) FROM dbops.audit_log;

SELECT dbops.fn_run_automations_delete_block('AUTO', ARRAY['dbops'], false);

SELECT has_trigger('dbops', 'tst_delete_block_audit', 'trg_tst_delete_block_audit_a10_delete_block_dlt',
    '4. il giro vero crea il trigger');

SELECT ok(EXISTS (
    SELECT 1 FROM dbops.audit_log a
     WHERE a.id > (SELECT ultimo_id FROM _prima)
       AND a.function_name = 'dbops.fn_run_automations_delete_block'
       AND a.status = 'OK' AND NOT a.dry_run
       AND a.params ->> 'table'   = 'dbops.tst_delete_block_audit'
       AND a.params ->> 'trigger' = 'trg_tst_delete_block_audit_a10_delete_block_dlt'
       AND a.params ->> 'action'  = 'CREATE_TRIGGER'),
    '5. giro vero: il trigger creato lascia una riga OK CREATE_TRIGGER');

SELECT ok(EXISTS (
    SELECT 1 FROM dbops.audit_log a
     WHERE a.id > (SELECT ultimo_id FROM _prima)
       AND a.function_name = 'dbops.fn_run_automations_delete_block'
       AND a.status = 'WARN' AND NOT a.dry_run
       AND a.params ->> 'table'  = 'dbops.tst_delete_block_sparita'
       AND a.params ->> 'reason' = 'TABLE_NOT_FOUND'),
    '6. giro vero: la tabella sparita lascia WARN TABLE_NOT_FOUND anche qui');

TRUNCATE _prima;
INSERT INTO _prima SELECT COALESCE(max(id), 0) FROM dbops.audit_log;

SELECT dbops.fn_run_automations_delete_block('AUTO', ARRAY['dbops'], false);

SELECT is((SELECT count(*) FROM dbops.audit_log a
            WHERE a.id > (SELECT ultimo_id FROM _prima)
              AND a.function_name = 'dbops.fn_run_automations_delete_block'
              AND a.params ->> 'table' = 'dbops.tst_delete_block_audit'),
          0::bigint,
          '7. un secondo giro col trigger gia'' presente non registra niente: non e'' un''azione');

SELECT * FROM finish();
ROLLBACK;
