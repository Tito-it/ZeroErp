-- pgTAP test per Zero ERP
--
-- Test: dbops.fn_get_lookup_codici - filtro asse obsoleto_dal
--       (brief-db-obsoleto-dal-filtro-lookup-e-guard, Obiettivo 1)
--
-- Indice test (1..6):
--  1) default (p_includi_obsoleti omesso = true): mostra TUTTI (incl. obsoleti)
--  2) p_includi_obsoleti=false: esclude obsoleto_dal <= oggi (OBS_PAST assente)
--  3) p_includi_obsoleti=false: record selezionabile (obsoleto_dal NULL) presente
--  4) p_includi_obsoleti=false: ritiro PROGRAMMATO (obsoleto_dal futura) presente
--  5) tabella SENZA colonna obsoleto_dal: lista intera anche con includi=false
--  6) tabella con obsoleto_dal NON date: errore struttura
-- ------------------------------------------------------------
BEGIN;

-- ⚠️ Vincoli DIFFERITI: senza questa riga il test smetterebbe di verificarli.
--   Un trigger DEFERRABLE INITIALLY DEFERRED scatta al COMMIT, e qui il COMMIT
--   non arriva mai (si chiude in ROLLBACK): sarebbero saltati in silenzio, e il
--   file sarebbe verde per sottrazione. IMMEDIATE li riporta a scattare a fine
--   di ogni istruzione. In testa e non in coda: in coda scatterebbero dopo il
--   cleanup, su righe ormai cancellate.
--   Brief: brief-db-pgtap-runner-rls-baseline §19.
SET CONSTRAINTS ALL IMMEDIATE;

-- Contesto applicativo: questo test gira come gira l'applicazione (ruolo
-- OPERATORE + RLS attiva), non come owner. Senza, con FORCE ROW LEVEL
-- SECURITY disattivo l'owner salta la RLS e il test non la esercita mai.
-- Brief: brief-db-pgtap-runner-rls-baseline §8.
DO $ctx$ BEGIN PERFORM script.fn_pgtap_set_contesto_operatore(); END $ctx$;

SELECT plan(6);

-- =========================================================
-- Fixture: 3 tipi_prestazione con i 3 stati dell'asse obsoleto_dal.
-- attivo=true su tutti (l'asse obsoleto e' separato da attivo).
-- =========================================================
INSERT INTO pratiche.tipi_prestazione (codice, codice_interno, descrizione, attivo, obsoleto_dal)
VALUES
  ('ZZTEST_OBS_PAST', 'ZZTEST_OBS_PAST', 'test obsoleto (passato)',       true, script.fn_data_operativa() - 1),
  ('ZZTEST_OBS_NULL', 'ZZTEST_OBS_NULL', 'test selezionabile (null)',     true, NULL),
  ('ZZTEST_OBS_FUT',  'ZZTEST_OBS_FUT',  'test ritiro programmato (fut)', true, script.fn_data_operativa() + 30);

-- 1) default = mostra tutto (retro-compat): i 3 record di test sono presenti.
SELECT is(
  (SELECT count(*)
     FROM dbops.fn_get_lookup_codici(
            p_rel => 'pratiche.tipi_prestazione'::regclass,
            p_limit => NULL)
    WHERE codice_interno LIKE 'ZZTEST_OBS%'),
  3::bigint,
  '1. default (includi_obsoleti=true): tutti e 3 i record presenti'
);

-- 2) includi_obsoleti=false: l'obsoleto passato e' escluso (restano 2).
SELECT is(
  (SELECT count(*)
     FROM dbops.fn_get_lookup_codici(
            p_rel => 'pratiche.tipi_prestazione'::regclass,
            p_includi_obsoleti => false,
            p_limit => NULL)
    WHERE codice_interno LIKE 'ZZTEST_OBS%'),
  2::bigint,
  '2. includi_obsoleti=false: esclude solo l''obsoleto passato (restano 2)'
);

-- 3) includi_obsoleti=false: il record selezionabile (NULL) e' presente.
SELECT is(
  (SELECT count(*)
     FROM dbops.fn_get_lookup_codici(
            p_rel => 'pratiche.tipi_prestazione'::regclass,
            p_includi_obsoleti => false,
            p_limit => NULL)
    WHERE codice_interno = 'ZZTEST_OBS_NULL'),
  1::bigint,
  '3. includi_obsoleti=false: record con obsoleto_dal NULL selezionabile'
);

-- 4) includi_obsoleti=false: il ritiro programmato (futura) e' ancora presente.
SELECT is(
  (SELECT count(*)
     FROM dbops.fn_get_lookup_codici(
            p_rel => 'pratiche.tipi_prestazione'::regclass,
            p_includi_obsoleti => false,
            p_limit => NULL)
    WHERE codice_interno = 'ZZTEST_OBS_FUT'),
  1::bigint,
  '4. includi_obsoleti=false: obsoleto_dal futura (ritiro programmato) ancora selezionabile'
);

-- =========================================================
-- 5) Tabella SENZA colonna obsoleto_dal: il filtro non si applica,
--    la lista viene restituita comunque (degradazione trasparente,
--    come gia' avviene per attivo).
-- =========================================================
CREATE TEMP TABLE zztest_lookup_no_obs (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codice      text,
  descrizione text
);
INSERT INTO zztest_lookup_no_obs (codice, descrizione)
VALUES ('A', 'Alpha'), ('B', 'Beta');

SELECT is(
  (SELECT count(*)
     FROM dbops.fn_get_lookup_codici(
            p_rel => 'zztest_lookup_no_obs'::regclass,
            p_includi_obsoleti => false,
            p_limit => NULL)),
  2::bigint,
  '5. tabella senza obsoleto_dal: lista intera anche con includi_obsoleti=false'
);

-- =========================================================
-- 6) Tabella con obsoleto_dal di tipo NON date: errore struttura
--    (il check di tipo e' simmetrico a quello su attivo boolean).
-- =========================================================
CREATE TEMP TABLE zztest_lookup_bad_obs (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codice       text,
  descrizione  text,
  obsoleto_dal text   -- volutamente NON date
);
INSERT INTO zztest_lookup_bad_obs (codice, descrizione, obsoleto_dal)
VALUES ('A', 'Alpha', 'non-una-data');

SELECT throws_ok(
  $$ SELECT * FROM dbops.fn_get_lookup_codici(
                     p_rel => 'zztest_lookup_bad_obs'::regclass,
                     p_includi_obsoleti => false,
                     p_limit => NULL) $$,
  NULL, NULL,
  '6. obsoleto_dal non date: errore struttura tabella'
);

SELECT * FROM finish();
ROLLBACK;
