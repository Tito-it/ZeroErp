-- pgtap-runner: owner
-- pgtap-runner-motivo: CREATE TABLE dbops._test_overlap_wp / _test_overlap_tot: l'automazione risolve
--   schema.tabella dal registry e ci applica sopra un EXCLUDE reale.
-- pgTAP test per Zero ERP
--
-- Test: fn_apply_automazione_overlap con where_predicate (EXCLUDE parziali)
--       Fase 1 / refactor-overlap-v2.
--
-- Elenco test:
--  1) where_predicate valorizzato: fn_apply crea un EXCLUDE (contype x)
--  2) la definizione del constraint contiene la coda WHERE (attivo)
--  3) due righe ATTIVE sovrapposte sono bloccate (exclusion_violation 23P01)
--  4) una riga DISATTIVA sovrapposta e' ammessa (fuori dal predicato)
--  5) where_predicate NULL: fn_apply crea un EXCLUDE totale
--  6) il constraint totale NON contiene alcuna coda WHERE
--
-- Sandbox in schema dbops. Il runner pgTAP esegue ogni file in transazione e
-- fa rollback; in piu' il test si auto-pulisce in coda (DROP + DELETE) per non
-- lasciare residui anche se lanciato direttamente in autocommit (psql -f).
-- ------------------------------------------------------------

-- ⚠️ Transazione, e non e' una formalita'. Il cleanup di questo file sta in
--   coda: col runner vero (pg_prove gira con ON_ERROR_STOP) un fallimento a
--   meta' non ci arriva mai, e i dati di prova restano nel database a rompere
--   la corsa successiva — che vede un rosso non suo.
--   Brief: brief-db-pgtap-runner-rls-baseline §15.3.
BEGIN;

-- ⚠️ Vincoli DIFFERITI: senza questa riga il test smetterebbe di verificarli.
--   Un trigger DEFERRABLE INITIALLY DEFERRED scatta al COMMIT, e qui il COMMIT
--   non arriva mai (si chiude in ROLLBACK): sarebbero saltati in silenzio, e il
--   file diventerebbe verde per sottrazione. Nel DB ce ne sono 365.
--   IMMEDIATE li riporta a scattare a fine di OGNI istruzione — cioe' esatta-
--   mente come si comportavano prima, quando il file girava in autocommit e
--   ogni istruzione era una transazione a se'. In testa e non in coda apposta:
--   in coda scatterebbero tutti insieme DOPO il cleanup, su righe ormai
--   cancellate. Brief: brief-db-pgtap-runner-rls-baseline §17.
SET CONSTRAINTS ALL IMMEDIATE;

-- Contesto applicativo: questo test gira come gira l'applicazione (ruolo
-- OPERATORE + RLS attiva), non come owner. Senza, con FORCE ROW LEVEL
-- SECURITY disattivo l'owner salta la RLS e il test non la esercita mai.
-- Brief: brief-db-pgtap-runner-rls-baseline §8.
DO $ctx$ BEGIN PERFORM script.fn_pgtap_set_contesto_operatore(); END $ctx$;

SELECT plan(6);

-- Pulizia preventiva (in caso di residui da un run precedente non rollbackato)
DROP TABLE IF EXISTS dbops._test_overlap_wp  CASCADE;
DROP TABLE IF EXISTS dbops._test_overlap_tot CASCADE;
DELETE FROM dbops.automazione_overlap WHERE target_table LIKE '\_test\_overlap%';

-- ============================================================
-- Sandbox 1 — vincolo PARZIALE (where_predicate = 'attivo IS TRUE')
-- ============================================================
CREATE TABLE dbops._test_overlap_wp (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chiave_id   integer NOT NULL,
  attivo      boolean NOT NULL DEFAULT true,
  valido_dal  date    NOT NULL,
  valido_al   date
);

INSERT INTO dbops.automazione_overlap
  (target_schema, target_table, key_columns, valido_dal_col, valido_al_col,
   range_bounds, constraint_name, active, exec_mode, where_predicate)
VALUES
  ('dbops', '_test_overlap_wp', ARRAY['chiave_id'], 'valido_dal', 'valido_al',
   '[]', 'ex__test_overlap_wp_no_overlap', true, 'AUTO', 'attivo IS TRUE');

SELECT dbops.fn_apply_automazione_overlap('AUTO', false);

-- 1) EXCLUDE creato
SELECT ok(
  EXISTS (
    SELECT 1 FROM pg_constraint con
      JOIN pg_class c ON c.oid = con.conrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = 'dbops' AND c.relname = '_test_overlap_wp'
       AND con.contype = 'x' AND con.conname = 'ex__test_overlap_wp_no_overlap'
  ),
  'where_predicate valorizzato: fn_apply crea un EXCLUDE (contype x)'
);

-- 2) la definizione contiene WHERE + il predicato
SELECT ok(
  (SELECT pg_get_constraintdef(con.oid)
     FROM pg_constraint con
     JOIN pg_class c ON c.oid = con.conrelid
     JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'dbops' AND c.relname = '_test_overlap_wp' AND con.contype = 'x'
  ) ILIKE '%WHERE%attivo%',
  'La definizione del constraint contiene la coda WHERE (attivo)'
);

-- riga base attiva
INSERT INTO dbops._test_overlap_wp (chiave_id, attivo, valido_dal, valido_al)
VALUES (1, true, DATE '2026-01-01', DATE '2026-12-31');

-- 3) due righe ATTIVE sovrapposte -> bloccate
SELECT throws_ok(
  $$ INSERT INTO dbops._test_overlap_wp (chiave_id, attivo, valido_dal, valido_al)
     VALUES (1, true, DATE '2026-06-01', DATE '2026-08-01') $$,
  '23P01',
  NULL,
  'Due righe ATTIVE sovrapposte: bloccate dall''EXCLUDE parziale'
);

-- 4) riga DISATTIVA sovrapposta -> ammessa (esclusa dal predicato)
SELECT lives_ok(
  $$ INSERT INTO dbops._test_overlap_wp (chiave_id, attivo, valido_dal, valido_al)
     VALUES (1, false, DATE '2026-06-01', DATE '2026-08-01') $$,
  'Riga DISATTIVA sovrapposta: ammessa (fuori dal predicato WHERE attivo)'
);

-- ============================================================
-- Sandbox 2 — vincolo TOTALE (where_predicate NULL)
-- ============================================================
CREATE TABLE dbops._test_overlap_tot (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chiave_id   integer NOT NULL,
  valido_dal  date    NOT NULL,
  valido_al   date
);

INSERT INTO dbops.automazione_overlap
  (target_schema, target_table, key_columns, valido_dal_col, valido_al_col,
   range_bounds, constraint_name, active, exec_mode, where_predicate)
VALUES
  ('dbops', '_test_overlap_tot', ARRAY['chiave_id'], 'valido_dal', 'valido_al',
   '[]', 'ex__test_overlap_tot_no_overlap', true, 'AUTO', NULL);

SELECT dbops.fn_apply_automazione_overlap('AUTO', false);

-- 5) EXCLUDE totale creato
SELECT ok(
  EXISTS (
    SELECT 1 FROM pg_constraint con
      JOIN pg_class c ON c.oid = con.conrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = 'dbops' AND c.relname = '_test_overlap_tot'
       AND con.contype = 'x' AND con.conname = 'ex__test_overlap_tot_no_overlap'
  ),
  'where_predicate NULL: fn_apply crea un EXCLUDE totale'
);

-- 6) la definizione NON contiene WHERE
SELECT ok(
  (SELECT pg_get_constraintdef(con.oid)
     FROM pg_constraint con
     JOIN pg_class c ON c.oid = con.conrelid
     JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'dbops' AND c.relname = '_test_overlap_tot' AND con.contype = 'x'
  ) NOT ILIKE '%WHERE%',
  'EXCLUDE totale: nessuna coda WHERE'
);

-- Cleanup: rimuove sandbox e righe di config (idempotente).
-- Necessario per run diretti in autocommit; ininfluente sotto runner con rollback.
DROP TABLE IF EXISTS dbops._test_overlap_wp  CASCADE;
DROP TABLE IF EXISTS dbops._test_overlap_tot CASCADE;
DELETE FROM dbops.automazione_overlap WHERE target_table LIKE '\_test\_overlap%';

SELECT * FROM finish();

-- Il ROLLBACK e' la garanzia: comunque vada — verde, rosso, o morto a meta' —
-- questo file non lascia nulla dietro di se'. Le DELETE del cleanup restano
-- perche' dove sono un'asserzione devono girare davvero.
ROLLBACK;
