-- pgTAP test per Zero ERP
-- Funzioni: dbops.fn_apply_cleanup_at, dbops.fn_purge_cleanup_expired,
--           dbops.fn_run_automations_cleanup
-- ------------------------------------------------------------
-- Indice test
-- 1) Presenza fn_apply_cleanup_at
-- 2) Presenza fn_purge_cleanup_expired
-- 3) Presenza fn_run_automations_cleanup
-- 4) Inserimento dataset di test
-- 5) fn_apply_cleanup_at dry_run conteggio righe
-- 6) fn_apply_cleanup_at update effettivo
-- 7) cleanup_at valorizzato su tutte le righe
-- 8) fn_purge_cleanup_expired dry_run conteggio scaduti
-- 9) fn_purge_cleanup_expired delete effettivo
-- 10) Verifica righe residue dopo purge helper
-- 11) Orchestratore: esclusione attiva non elimina
-- 12) Orchestratore: esclusione disattivata elimina
-- ------------------------------------------------------------

BEGIN;

-- Contesto applicativo: questo test gira come gira l'applicazione (ruolo
-- OPERATORE + RLS attiva), non come owner. Senza, con FORCE ROW LEVEL
-- SECURITY disattivo l'owner salta la RLS e il test non la esercita mai.
-- Brief: brief-db-pgtap-runner-rls-baseline §8.
DO $ctx$ BEGIN PERFORM script.fn_pgtap_set_contesto_operatore(); END $ctx$;

SELECT plan(12);

CREATE TEMP TABLE tmp_cleanup_ctx AS
SELECT to_char(clock_timestamp(), 'YYYYMMDDHH24MISSMS') AS tag;

SELECT ok(
  EXISTS (
    SELECT 1
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'dbops'
      AND p.proname = 'fn_apply_cleanup_at'
  ),
  'Presente funzione dbops.fn_apply_cleanup_at'
);

SELECT ok(
  EXISTS (
    SELECT 1
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'dbops'
      AND p.proname = 'fn_purge_cleanup_expired'
  ),
  'Presente funzione dbops.fn_purge_cleanup_expired'
);

SELECT ok(
  EXISTS (
    SELECT 1
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'dbops'
      AND p.proname = 'fn_run_automations_cleanup'
  ),
  'Presente funzione dbops.fn_run_automations_cleanup'
);

CREATE TABLE IF NOT EXISTS dbops.tst_cleanup_framework (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payload text,
  data_insert timestamptz NOT NULL DEFAULT now(),
  cleanup_at timestamptz
);

TRUNCATE TABLE dbops.tst_cleanup_framework;

INSERT INTO dbops.tst_cleanup_framework (payload, data_insert, cleanup_at)
VALUES
  ('row_old', now() - interval '15 days', NULL),
  ('row_recent', now() - interval '1 day', NULL);

SELECT is(
  (SELECT count(*)::int FROM dbops.tst_cleanup_framework),
  2,
  'Inserite 2 righe nel dataset di test'
);

SELECT is(
  dbops.fn_apply_cleanup_at(
    'dbops',
    'tst_cleanup_framework',
    'cleanup_at',
    'data_insert',
    10,
    false,
    true
  ),
  2,
  'fn_apply_cleanup_at dry_run: 2 righe candidate'
);

SELECT is(
  dbops.fn_apply_cleanup_at(
    'dbops',
    'tst_cleanup_framework',
    'cleanup_at',
    'data_insert',
    10,
    false,
    false
  ),
  2,
  'fn_apply_cleanup_at update: 2 righe aggiornate'
);

SELECT is(
  (SELECT count(*)::int FROM dbops.tst_cleanup_framework WHERE cleanup_at IS NOT NULL),
  2,
  'cleanup_at valorizzato su tutte le righe'
);

SELECT is(
  dbops.fn_purge_cleanup_expired(
    'dbops',
    'tst_cleanup_framework',
    'cleanup_at',
    5000,
    true
  ),
  1,
  'fn_purge_cleanup_expired dry_run: 1 riga scaduta'
);

SELECT is(
  dbops.fn_purge_cleanup_expired(
    'dbops',
    'tst_cleanup_framework',
    'cleanup_at',
    5000,
    false
  ),
  1,
  'fn_purge_cleanup_expired delete: 1 riga eliminata'
);

SELECT is(
  (SELECT count(*)::int FROM dbops.tst_cleanup_framework),
  1,
  'Resta 1 riga dopo purge helper'
);

INSERT INTO dbops.tst_cleanup_framework (payload, data_insert, cleanup_at)
VALUES ('row_for_runner', now() - interval '30 days', now() - interval '1 hour');

CREATE TEMP TABLE tmp_cleanup_scope AS
SELECT dbops.fn_table_in_scope('dbops', 'tst_cleanup_framework') AS in_scope;

CREATE TEMP TABLE tmp_cleanup_rule AS
WITH ins AS (
  INSERT INTO dbops.automation_rules_tbl (
    enabled,
    rule_type,
    target_schema,
    target_table,
    exec_mode,
    name_template,
    existence_strategy,
    params,
    priority,
    note
  )
  VALUES (
    true,
    'CLEANUP_PURGE',
    'dbops',
    'tst_cleanup_framework',
    'AUTO',
    NULL,
    'BY_NAME',
    '{"cleanup_column":"cleanup_at","batch_limit":5000}'::jsonb,
    10,
    'pgtap_cleanup_' || (SELECT tag FROM tmp_cleanup_ctx)
  )
  RETURNING id
)
SELECT id FROM ins;

INSERT INTO dbops.automation_cleanup_exclusions (schema_name, table_name, enabled, reason)
VALUES ('dbops', 'tst_cleanup_framework', true, 'pgtap exclusion')
ON CONFLICT (schema_name, table_name)
DO UPDATE
SET enabled = EXCLUDED.enabled,
    reason = EXCLUDED.reason;

SELECT dbops.fn_run_automations_cleanup('AUTO', ARRAY['dbops'], false);

SELECT CASE
  WHEN (SELECT in_scope FROM tmp_cleanup_scope) THEN
    is(
      (SELECT count(*)::int FROM dbops.tst_cleanup_framework WHERE payload = 'row_for_runner'),
      1,
      'Orchestratore: con esclusione attiva la riga resta'
    )
  ELSE
    ok(true, 'Scope non include tabella test: verifica orchestratore skip')
END;

UPDATE dbops.automation_cleanup_exclusions
SET enabled = false
WHERE schema_name = 'dbops'
  AND table_name = 'tst_cleanup_framework';

SELECT dbops.fn_run_automations_cleanup('AUTO', ARRAY['dbops'], false);

SELECT CASE
  WHEN (SELECT in_scope FROM tmp_cleanup_scope) THEN
    is(
      (SELECT count(*)::int FROM dbops.tst_cleanup_framework WHERE payload = 'row_for_runner'),
      0,
      'Orchestratore: con esclusione disattivata elimina la riga scaduta'
    )
  ELSE
    ok(true, 'Scope non include tabella test: verifica orchestratore skip')
END;

DELETE FROM dbops.automation_cleanup_exclusions
WHERE schema_name = 'dbops'
  AND table_name = 'tst_cleanup_framework';

DELETE FROM dbops.automation_rules_tbl
WHERE id IN (SELECT id FROM tmp_cleanup_rule);

DROP TABLE IF EXISTS dbops.tst_cleanup_framework;

SELECT * FROM finish();

ROLLBACK;
