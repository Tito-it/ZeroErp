-- pgtap-runner-motivo: CREATE TABLE dbops.tst_scadenza_*: la regola della scadenza si collauda su
--   tabelle vere, con le loro regole, le loro esclusioni e il trigger alla nascita, e dbops e'
--   schema di strumenti DBA su cui il ruolo applicativo non ha (giustamente) CREATE.
-- pgTAP test per Zero ERP
--
-- La scadenza ha una regola sola: dbops.fn_cleanup_at_regola, letta dal trigger alla nascita
-- (dbops.trgfn_cleanup_at_alla_nascita), dal runner sul pregresso
-- (dbops.fn_run_automations_cleanup) e dal login (script.fn_registra_tentativo_login).
-- Brief: brief-db-revisione-dbops, giro 10b, blocco 10b-3 (D16 con N3).
--
-- ⭐ COSA PRESIDIA: la stessa riga riceve la stessa scadenza da chi la scrive alla nascita e da
--   chi la scrive dopo. Prima il trigger prendeva la regola senza le esclusioni, partiva da now()
--   senza colonna base e da now() anche con la base NULL; il runner applicava le esclusioni e la
--   catena data_insert → executed_at → occurred_at → created_at, e saltava le righe con la base
--   NULL. I casi si costruiscono qui: due regole sulla stessa tabella, una tabella che ha solo
--   executed_at, una esclusa, una senza colonna base, una riga con la base NULL.
--
-- Elenco test (plan 14):
--  1)    il risolutore sceglie la regola piu' specifica (priority) e la base dalla catena
--  2)    il trigger scrive base + ttl della regola scelta
--  3)    ⭐ il runner, sulla stessa riga riportata a NULL, scrive la stessa scadenza
--  4)    base NULL sulla riga: il trigger lascia cleanup_at NULL...
--  5)    ...e il runner non la tocca
--  6)    tabella esclusa: il risolutore dice EXCLUDED
--  7)    tabella esclusa: il trigger scrive NULL anche se il chiamante passa una scadenza
--  8)    tabella esclusa: il runner non le da' una scadenza
--  9)    tabella senza colonna base: MISSING_BASE_TS_COLUMN, e il trigger scrive NULL
-- 10)    tabella senza cleanup_at: il risolutore dice NO_CLEANUP_COLUMN
-- 11)    le tre tabelle del login hanno la base ultimo_fallimento_at: il login scrive now() + ttl
--        perche' scrive ultimo_fallimento_at = now() nella stessa istruzione
-- 12)    dbops.fn_cleanup_at_params non c'e' piu'
-- 13)    nessuna regola del registro porta cleanup_column
-- 14)    nessuna funzione legge una chiave cleanup_column
-- ------------------------------------------------------------

BEGIN;

-- ⚠️ Vincoli DIFFERITI: senza questa riga il test smetterebbe di verificarli.
SET CONSTRAINTS ALL IMMEDIATE;

DO $ctx$ BEGIN PERFORM script.fn_pgtap_set_contesto_operatore(); END $ctx$;

SELECT plan(14);

-- ============================================================
-- Fixture: quattro tabelle, le loro regole, un'esclusione, il trigger
-- ============================================================
-- Solo executed_at: la base, se la regola non la dichiara, la trova la catena.
CREATE TABLE dbops.tst_scadenza_due (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payload     text,
    executed_at timestamptz,
    cleanup_at  timestamptz);
CREATE TABLE dbops.tst_scadenza_esclusa (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payload     text,
    data_insert timestamptz NOT NULL DEFAULT now(),
    cleanup_at  timestamptz);
-- Nessuna colonna della catena.
CREATE TABLE dbops.tst_scadenza_senza_base (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payload     text,
    cleanup_at  timestamptz);
CREATE TABLE dbops.tst_scadenza_senza_colonna (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_insert timestamptz NOT NULL DEFAULT now());

CREATE TRIGGER trg_tst_scadenza_due_m50_cleanup_at_ins BEFORE INSERT ON dbops.tst_scadenza_due
    FOR EACH ROW EXECUTE FUNCTION dbops.trgfn_cleanup_at_alla_nascita();
CREATE TRIGGER trg_tst_scadenza_esclusa_m50_cleanup_at_ins BEFORE INSERT ON dbops.tst_scadenza_esclusa
    FOR EACH ROW EXECUTE FUNCTION dbops.trgfn_cleanup_at_alla_nascita();
CREATE TRIGGER trg_tst_scadenza_senza_base_m50_cleanup_at_ins BEFORE INSERT ON dbops.tst_scadenza_senza_base
    FOR EACH ROW EXECUTE FUNCTION dbops.trgfn_cleanup_at_alla_nascita();

-- ⭐ LO SCOPE: senza, il runner non guarda queste tabelle e le asserzioni sul runner
--   passerebbero senza verificare niente.
INSERT INTO dbops.automation_scope (schema_name, table_like)
VALUES ('dbops', 'tst_scadenza_due'), ('dbops', 'tst_scadenza_esclusa'), ('dbops', 'tst_scadenza_senza_base')
ON CONFLICT DO NOTHING;

-- Due regole sulla stessa tabella: vince la priority minore (7 giorni), non l'ultima.
INSERT INTO dbops.automation_rules_tbl
       (enabled, rule_type, target_schema, target_table, exec_mode, name_template, params, priority, note)
VALUES (true, 'CLEANUP_AT', 'dbops', 'tst_scadenza_due',        'AUTO', NULL, '{"ttl_days": 7}',  5, 'pgTAP regola unica'),
       (true, 'CLEANUP_AT', 'dbops', 'tst_scadenza_due',        'AUTO', NULL, '{"ttl_days": 99}', 6, 'pgTAP regola unica'),
       (true, 'CLEANUP_AT', 'dbops', 'tst_scadenza_esclusa',    'AUTO', NULL, '{"ttl_days": 7}',  5, 'pgTAP regola unica'),
       (true, 'CLEANUP_AT', 'dbops', 'tst_scadenza_senza_base', 'AUTO', NULL, '{"ttl_days": 7}',  5, 'pgTAP regola unica');

INSERT INTO dbops.automation_cleanup_exclusions (schema_name, table_name, enabled, reason)
VALUES ('dbops', 'tst_scadenza_esclusa', true, 'pgTAP regola unica')
ON CONFLICT (schema_name, table_name) DO UPDATE SET enabled = true;

-- ============================================================
-- 1-3) Due regole, base dalla catena: trigger e runner dicono la stessa data
-- ============================================================
SELECT results_eq(
    $q$SELECT r.ttl_days, r.base_ts_column, r.motivo_salto
         FROM dbops.fn_cleanup_at_regola('dbops', 'tst_scadenza_due') r$q$,
    $q$VALUES (7, 'executed_at'::text, NULL::text)$q$,
    '1) il risolutore sceglie la regola piu'' specifica (7 giorni, non 99) e la base dalla catena (executed_at)');

-- ⚠️ La base e' adesso, non una data fissa del passato: il runner, dopo la scadenza,
--   fa anche il purge (la *all), e una riga gia' scaduta sparirebbe prima del test 3.
INSERT INTO dbops.tst_scadenza_due (payload, executed_at)
VALUES ('con_base', now()),
       ('base_null', NULL);

SELECT is(
    (SELECT cleanup_at FROM dbops.tst_scadenza_due WHERE payload = 'con_base'),
    now() + interval '7 days',
    '2) il trigger alla nascita scrive executed_at + 7 giorni');

CREATE TEMP TABLE _alla_nascita AS
SELECT cleanup_at FROM dbops.tst_scadenza_due WHERE payload = 'con_base';

UPDATE dbops.tst_scadenza_due SET cleanup_at = NULL WHERE payload = 'con_base';

-- ⚠️ Il runner in un'istruzione SEPARATA dalle asserzioni: la snapshot di statement
--   legge PRIMA delle scritture.
SELECT dbops.fn_run_automations_cleanup('AUTO', ARRAY['dbops'], false);

SELECT is(
    (SELECT cleanup_at FROM dbops.tst_scadenza_due WHERE payload = 'con_base'),
    (SELECT cleanup_at FROM _alla_nascita),
    '3) ⭐ il runner, sulla stessa riga riportata a NULL, scrive la stessa scadenza del trigger');

-- ============================================================
-- 4-5) Base NULL sulla riga: nessuna scadenza, da nessuno dei due
-- ============================================================
SELECT is(
    (SELECT cleanup_at FROM dbops.tst_scadenza_due WHERE payload = 'base_null'),
    NULL::timestamptz,
    '4) base NULL sulla riga: il trigger lascia cleanup_at NULL (prima partiva da now())');

SELECT is(
    (SELECT cleanup_at FROM dbops.tst_scadenza_due WHERE payload = 'base_null'),
    NULL::timestamptz,
    '5) ...e il runner, appena girato, non la tocca: la scadenza arriva quando la base c''e''');

-- ============================================================
-- 6-8) Tabella esclusa
-- ============================================================
SELECT is(
    (SELECT r.motivo_salto FROM dbops.fn_cleanup_at_regola('dbops', 'tst_scadenza_esclusa') r),
    'EXCLUDED',
    '6) tabella esclusa: il risolutore dice EXCLUDED');

INSERT INTO dbops.tst_scadenza_esclusa (payload, cleanup_at)
VALUES ('esclusa', now() + interval '1 day');

SELECT is(
    (SELECT cleanup_at FROM dbops.tst_scadenza_esclusa WHERE payload = 'esclusa'),
    NULL::timestamptz,
    '7) tabella esclusa: il trigger scrive NULL anche se il chiamante passa una scadenza (prima la scriveva, e nessuno la purgava)');

INSERT INTO dbops.tst_scadenza_esclusa (payload) VALUES ('esclusa_dopo');
SELECT dbops.fn_run_automations_cleanup('AUTO', ARRAY['dbops'], false);

SELECT is(
    (SELECT count(*)::int FROM dbops.tst_scadenza_esclusa WHERE cleanup_at IS NOT NULL),
    0,
    '8) tabella esclusa: il runner non le da'' una scadenza');

-- ============================================================
-- 9-10) Colonna base o cleanup_at assenti
-- ============================================================
INSERT INTO dbops.tst_scadenza_senza_base (payload, cleanup_at)
VALUES ('senza_base', now() + interval '1 day');

SELECT ok(
    (SELECT r.motivo_salto = 'MISSING_BASE_TS_COLUMN' AND r.base_ts_column IS NULL
       FROM dbops.fn_cleanup_at_regola('dbops', 'tst_scadenza_senza_base') r)
    AND (SELECT cleanup_at IS NULL FROM dbops.tst_scadenza_senza_base WHERE payload = 'senza_base'),
    '9) tabella senza colonna base: MISSING_BASE_TS_COLUMN, e il trigger scrive NULL (prima partiva da now())');

SELECT is(
    (SELECT r.motivo_salto FROM dbops.fn_cleanup_at_regola('dbops', 'tst_scadenza_senza_colonna') r),
    'NO_CLEANUP_COLUMN',
    '10) tabella senza cleanup_at (la copre la *all): il risolutore dice NO_CLEANUP_COLUMN');

-- ============================================================
-- 11) Il login
-- ============================================================
SELECT results_eq(
    $q$SELECT t.tabella, r.base_ts_column, r.motivo_salto
         FROM (VALUES ('credenziali_provenienze'), ('nomi_tentati'), ('nomi_tentati_provenienze')) t(tabella)
         CROSS JOIN LATERAL dbops.fn_cleanup_at_regola('config', t.tabella) r
        ORDER BY t.tabella$q$,
    $q$VALUES ('credenziali_provenienze'::text,  'ultimo_fallimento_at'::text, NULL::text),
              ('nomi_tentati'::text,             'ultimo_fallimento_at'::text, NULL::text),
              ('nomi_tentati_provenienze'::text, 'ultimo_fallimento_at'::text, NULL::text)$q$,
    '11) le tre tabelle del login hanno la base ultimo_fallimento_at: il login scrive now() + ttl perche'' scrive ultimo_fallimento_at = now() nella stessa istruzione');

-- ============================================================
-- 12-14) La sede unica e la colonna fissa
-- ============================================================
SELECT hasnt_function('dbops', 'fn_cleanup_at_params', ARRAY['text', 'text'],
    '12) dbops.fn_cleanup_at_params non c''e'' piu'': la regola sta in dbops.fn_cleanup_at_regola');

SELECT is(
    (SELECT count(*)::int FROM dbops.automation_rules_tbl WHERE params ? 'cleanup_column'),
    0,
    '13) nessuna regola del registro porta cleanup_column: la colonna e'' cleanup_at, nome fisso');

SELECT is(
    (SELECT COALESCE(array_agg(p.oid::regprocedure::text ORDER BY 1), ARRAY[]::text[])
       FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
      WHERE n.nspname IN ('dbops', 'script', 'maintenance')
        AND p.prokind = 'f'
        AND pg_get_functiondef(p.oid) LIKE '%>>%''cleanup\_column''%'),
    ARRAY[]::text[],
    '14) nessuna funzione legge una chiave cleanup_column dai params');

SELECT * FROM finish();
ROLLBACK;
