-- pgtap-runner-motivo: CREATE TABLE dbops._test_overlap_kx: l'automazione risolve schema.tabella dal
--   registry e ci applica sopra un EXCLUDE reale, quindi una TEMP non serve.
-- pgTAP test per Zero ERP
--
-- Test: fn_apply_automazione_overlap con key_expressions (chiavi su espressione)
--       Fase 2 / refactor-overlap-v2 (opzione A esplicita).
--
-- Elenco test:
--  1) key_expressions valorizzato: fn_apply crea un EXCLUDE (contype x)
--  2) la definizione del constraint contiene l'espressione di chiave (COALESCE)
--  3) due righe con classe NULL e stessa chiave, sovrapposte -> bloccate
--     (COALESCE(classe,-1) rende i NULL uguali tra loro) (23P01)
--  4) due righe con classe NULL vs classe valorizzata, sovrapposte -> ammesse
--     (chiavi diverse)
--
-- Sandbox in schema dbops; il test si auto-pulisce (run sicuro anche in autocommit).
-- ------------------------------------------------------------

-- ⚠️ Transazione, e non e' una formalita'. Il cleanup di questo file sta in
--   coda: col runner vero (pg_prove gira con ON_ERROR_STOP) un fallimento a
--   meta' non ci arriva mai, e i dati di prova restano nel database a rompere
--   la corsa successiva — che vede un rosso non suo.
--   Brief: brief-db-pgtap-runner-rls-baseline §15.3.
BEGIN;

-- ⚠️ Vincoli DIFFERITI: senza questa riga il test smetterebbe di verificarli.
--   Un trigger DEFERRABLE INITIALLY DEFERRED scatta al COMMIT, e qui il COMMIT
--   non arriva mai (si chiude in ROLLBACK): sarebbero saltati in silenzio, e il
--   file diventerebbe verde per sottrazione. Nel DB ce ne sono 365.
--   IMMEDIATE li riporta a scattare a fine di OGNI istruzione — cioe' esatta-
--   mente come si comportavano prima, quando il file girava in autocommit e
--   ogni istruzione era una transazione a se'. In testa e non in coda apposta:
--   in coda scatterebbero tutti insieme DOPO il cleanup, su righe ormai
--   cancellate. Brief: brief-db-pgtap-runner-rls-baseline §17.
SET CONSTRAINTS ALL IMMEDIATE;

-- Contesto applicativo: questo test gira come gira l'applicazione (ruolo
-- OPERATORE + RLS attiva), non come owner. Senza, con FORCE ROW LEVEL
-- SECURITY disattivo l'owner salta la RLS e il test non la esercita mai.
-- Brief: brief-db-pgtap-runner-rls-baseline §8.
DO $ctx$ BEGIN PERFORM script.fn_pgtap_set_contesto_operatore(); END $ctx$;

SELECT plan(4);

-- Pulizia preventiva
DROP TABLE IF EXISTS dbops._test_overlap_kx CASCADE;
DELETE FROM dbops.automazione_overlap WHERE target_table = '_test_overlap_kx';

CREATE TABLE dbops._test_overlap_kx (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  k1          integer NOT NULL,
  classe      integer,            -- nullable: la chiave usa COALESCE(classe,-1)
  valido_dal  date    NOT NULL,
  valido_al   date
);

INSERT INTO dbops.automazione_overlap
  (target_schema, target_table, key_columns, key_expressions, valido_dal_col,
   valido_al_col, range_bounds, constraint_name, active, exec_mode, where_predicate)
VALUES
  ('dbops', '_test_overlap_kx', '["k1"]'::jsonb, '["COALESCE(classe, ''-1''::integer)"]'::jsonb,
   'valido_dal', 'valido_al', '[]', 'ex__test_overlap_kx_no_overlap', true, 'AUTO', NULL);

SELECT dbops.fn_apply_automazione_overlap('AUTO', false);

-- 1) EXCLUDE creato
SELECT ok(
  EXISTS (
    SELECT 1 FROM pg_constraint con
      JOIN pg_class c ON c.oid = con.conrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = 'dbops' AND c.relname = '_test_overlap_kx'
       AND con.contype = 'x' AND con.conname = 'ex__test_overlap_kx_no_overlap'
  ),
  'key_expressions valorizzato: fn_apply crea un EXCLUDE (contype x)'
);

-- 2) la definizione contiene l'espressione COALESCE
SELECT ok(
  (SELECT pg_get_constraintdef(con.oid)
     FROM pg_constraint con
     JOIN pg_class c ON c.oid = con.conrelid
     JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'dbops' AND c.relname = '_test_overlap_kx' AND con.contype = 'x'
  ) ILIKE '%COALESCE%classe%',
  'La definizione del constraint contiene l''espressione di chiave (COALESCE)'
);

-- riga base: classe NULL
INSERT INTO dbops._test_overlap_kx (k1, classe, valido_dal, valido_al)
VALUES (1, NULL, DATE '2026-01-01', DATE '2026-12-31');

-- 3) due righe classe NULL, stessa k1, sovrapposte -> bloccate (NULL trattati uguali via COALESCE)
SELECT throws_ok(
  $$ INSERT INTO dbops._test_overlap_kx (k1, classe, valido_dal, valido_al)
     VALUES (1, NULL, DATE '2026-06-01', DATE '2026-08-01') $$,
  '23P01',
  NULL,
  'Due righe classe NULL sovrapposte: bloccate (COALESCE rende i NULL uguali)'
);

-- 4) classe NULL vs classe valorizzata, sovrapposte -> ammesse (chiavi diverse)
SELECT lives_ok(
  $$ INSERT INTO dbops._test_overlap_kx (k1, classe, valido_dal, valido_al)
     VALUES (1, 5, DATE '2026-06-01', DATE '2026-08-01') $$,
  'Classe NULL vs classe valorizzata sovrapposte: ammesse (chiavi diverse)'
);

-- Cleanup (idempotente)
DROP TABLE IF EXISTS dbops._test_overlap_kx CASCADE;
DELETE FROM dbops.automazione_overlap WHERE target_table = '_test_overlap_kx';

SELECT * FROM finish();

-- Il ROLLBACK e' la garanzia: comunque vada — verde, rosso, o morto a meta' —
-- questo file non lascia nulla dietro di se'. Le DELETE del cleanup restano
-- perche' dove sono un'asserzione devono girare davvero.
ROLLBACK;
